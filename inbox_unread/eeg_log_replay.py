def calc_power_nw(voltage_uv, r_ohm=1000.0):
    voltage_v = voltage_uv * 1e-6
    return ((voltage_v ** 2) / r_ohm) * 1e9

def main():
    print("=== 内蔵ログリプレイ＆リアルタイム解析エンジン ===")
    print(f"解析サンプル数: {len(LOG_HISTORY)} | 依存ライブラリ: 標準ライブラリのみ")
    print("----------------------------------------------------------------------")

    ch1_sq_sum = 0.0
    max_power = 0.0
    peak_timestamp = 0.0

    for item in LOG_HISTORY:
        t = item["t"]
        ch1 = item["ch1"]
        ch2 = item["ch2"]
        power_nw = calc_power_nw(ch1)

        # 統計量の積算
        ch1_sq_sum += ch1 ** 2
        if power_nw > max_power:
            max_power = power_nw
            peak_timestamp = t

        # 再現再生（0.05秒間隔の滑らか表示）
        print(f"[{t:6.2f}s] Ch1: {ch1:6.2f} uV | Ch2: {ch2:6.2f} uV | Power: {power_nw:9.6f} nW", end="\r")
        time.sleep(0.05)

    # ログ全体の解析結果を出力
    rms_v = math.sqrt(ch1_sq_sum / len(LOG_HISTORY))
    print("\n----------------------------------------------------------------------")
    print("【解析結果】")
    print(f" - 全データCh1 RMS実効値: {rms_v:.4f} uV")
    print(f" - 瞬間最大電力ピーク   : {max_power:.6f} nW (タイムスタンプ: {peak_timestamp:.2f}s)")
    print("=== リプレイ＆特徴量抽出セッション完了 ===")

if __name__ == "__main__":
    main()
